"""Machine-readable and human-readable reports. All numbers are taken from the summary computed by training."""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, Optional

import numpy as np

DISCLAIMER = ("Trained and evaluated on synthetic data generated by this repository. Metrics describe how well the model "
              "recovers the generator's assumptions, not real-world or clinical performance. Prototype only.")


def _pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def _row(label: str, m: Dict[str, Any]) -> str:
    cm = m["confusion_matrix"]
    return (f"| {label} | {m['threshold']:.2f} | {m['precision']:.3f} | {m['recall']:.3f} | {m['f1']:.3f} | "
            f"{cm['tp']} | {cm['fp']} | {cm['fn']} | {cm['tn']} | {_pct(m['flagged_share'])} |")


def write_reports(report_dir: Path, s: Dict[str, Any], p_test: np.ndarray, y_test: np.ndarray) -> None:
    """metrics.json, evaluation_report.md, feature_importance.{csv,json}, calibration_curve.png, ramesh_demo.{json,md}."""
    report_dir = Path(report_dir)
    report_dir.mkdir(parents=True, exist_ok=True)
    (report_dir / "metrics.json").write_text(json.dumps(
        {k: s[k] for k in ("model_version", "selected", "comparison", "best_per_family", "thresholds", "validation", "test",
                           "test_by_family", "split_sizes")}, indent=2, sort_keys=True) + "\n")
    _calibration_plot(report_dir / "calibration_curve.png", s["test"]["calibration"])
    if s["importance"]:
        import pandas as pd
        imp = pd.DataFrame(s["importance"])
        imp.to_csv(report_dir / "feature_importance.csv", index=False, float_format="%.4f")
        (report_dir / "feature_importance.json").write_text(json.dumps(s["importance"], indent=2) + "\n")
    (report_dir / "evaluation_report.md").write_text(_evaluation_markdown(s))
    if s["ramesh_demo"]:
        (report_dir / "ramesh_demo.json").write_text(json.dumps(s["ramesh_demo"], indent=2, sort_keys=True, default=str) + "\n")
        (report_dir / "ramesh_demo.md").write_text(_ramesh_markdown(s["ramesh_demo"], s["thresholds"]))


def _calibration_plot(path: Path, cal: Dict[str, Any]) -> None:
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(figsize=(4.5, 4.5), dpi=100)
    try:
        xs = [b["mean_predicted"] for b in cal["bins"]]
        ys = [b["observed_rate"] for b in cal["bins"]]
        ax.plot([0, 1], [0, 1], "--", color="grey", label="perfect")
        ax.plot(xs, ys, "o-", label=f"model (ECE {cal['ece']:.3f})")
        ax.set_xlabel("mean predicted dropout probability")
        ax.set_ylabel("observed dropout rate")
        ax.set_title("Calibration (held-out test)")
        ax.legend()
        fig.tight_layout()
        fig.savefig(path)
    finally:
        plt.close(fig)


def _evaluation_markdown(s: Dict[str, Any]) -> str:
    sel, th, val, test = s["selected"], s["thresholds"], s["validation"], s["test"]
    L = [f"# Retention model evaluation ({s['model_version']})", "", f"> {DISCLAIMER}", "",
         f"Split sizes: {s['split_sizes']}. The test split was used once, after model and thresholds were frozen.", "",
         "## Model comparison (validation set; used for selection)", "",
         "| Family | Params | ROC-AUC | PR-AUC | Brier | F1@0.5 | Recall@0.5 |", "|---|---|---|---|---|---|---|"]
    for fam, r in s["best_per_family"].items():
        mark = " **(selected)**" if fam == sel["family"] else ""
        L.append(f"| {fam}{mark} | {r['params']} | {r['val_roc_auc']:.3f} | {r['val_pr_auc']:.3f} | {r['val_brier']:.3f} | "
                 f"{r['val_f1_at_0.5']:.3f} | {r['val_recall_at_0.5']:.3f} |")
    L += ["", f"Selection rule: highest validation PR-AUC among non-baseline models, ties to the lower Brier score "
          f"({len(s['comparison'])} configurations were compared).", "",
          "## Test set, best configuration of each family (descriptive; not used for selection)", "",
          "| Family | ROC-AUC | PR-AUC | Brier | Precision@0.5 | Recall@0.5 |", "|---|---|---|---|---|---|"]
    for fam, r in s["test_by_family"].items():
        a = r["at_default_0.5"]
        L.append(f"| {fam} | {r['roc_auc']:.3f} | {r['pr_auc']:.3f} | {r['brier']:.3f} | {a['precision']:.3f} | {a['recall']:.3f} |")
    ci_r, ci_p = test["roc_auc_ci95"], test["pr_auc_ci95"]
    L += ["", f"## Selected model on the held-out test set (n={test['n']}, prevalence {_pct(test['prevalence'])})", "",
          f"- ROC-AUC {test['roc_auc']:.3f} (95% bootstrap CI {ci_r['lower']:.3f}-{ci_r['upper']:.3f})",
          f"- PR-AUC {test['pr_auc']:.3f} (95% CI {ci_p['lower']:.3f}-{ci_p['upper']:.3f}); a no-skill model scores {test['prevalence']:.3f}",
          f"- Brier {test['brier']:.3f}; expected calibration error {test['calibration']['ece']:.3f} (see `calibration_curve.png`)", "",
          "| Threshold | Value | Precision | Recall | F1 | TP | FP | FN | TN | Flagged |", "|---|---|---|---|---|---|---|---|---|---|"]
    for name in ("default_0.5", "operational", "high"):
        L.append(_row(name, test["at_threshold"][name]))
    vo = th["validation_at_operational"]
    L += ["", "## Threshold selection (validation data only)", "",
          f"- {th['criterion']}.",
          f"- Operational threshold **{th['operational_threshold']:.2f}**: validation recall {vo['recall']:.3f}, precision {vo['precision']:.3f}, "
          f"flags {_pct(vo['flagged_share'])} of participants.",
          f"- High-risk threshold **{th['high_threshold']:.2f}**" + (" (fallback: precision target never reached)" if th["high_threshold_fallback_used"] else
           f": validation precision {th['validation_at_high']['precision']:.3f}."),
          "- Risk levels: `low` below the operational threshold, `medium` between the two, `high` at or above the high threshold.", "",
          "### False negatives vs false positives", "",
          "A false negative is an at-risk participant the screen misses and who therefore gets no extra support; a false positive is a "
          "participant who receives an unnecessary (cheap, non-clinical) check-in. Because support actions are low-cost and the cost of "
          "losing a participant is high, the operational threshold weights recall twice as much as precision (F2) instead of using 0.5. "
          "The price is a larger flagged group and lower precision; compare the 0.5 and operational rows above. Change `f_beta` in "
          "`config.py` to move the trade-off.", ""]
    if s["importance"]:
        L += ["## Global feature importance (mean |SHAP|, risk-score points, test sample)", "", "| Feature | Mean abs | Mean signed |", "|---|---|---|"]
        L += [f"| {r['label']} | {r['mean_abs_contribution']:.2f} | {r['mean_signed_contribution']:+.2f} |" for r in s["importance"]]
        L.append("")
    L += ["## Caveats", "", f"- {DISCLAIMER}",
          f"- The test set has {test['n']} participants (~{int(round(test['prevalence'] * test['n']))} dropouts), so metrics carry wide uncertainty (see CIs).",
          "- Feature attributions are statistical, not causal.", ""]
    return "\n".join(L)


def _ramesh_markdown(demo: Dict[str, Any], th: Dict[str, Any]) -> str:
    f, p = demo["input"], demo["prediction"]
    L = ["# Ramesh demo prediction", "", f"> {DISCLAIMER}", "", "## Input (from the Phase 3 demo participants file)", "",
         "| Feature | Value |", "|---|---|"] + [f"| {k} | {v} |" for k, v in f.items()]
    L += ["", f"## Output ({p['model_version']})", "",
          f"- **Risk score: {p['risk_score']:.1f} / 100 - {p['risk_level'].upper()}** "
          f"(operational threshold {th['operational_threshold'] * 100:.0f}, high threshold {th['high_threshold'] * 100:.0f}; "
          f"cohort baseline {p['baseline_risk_score']})", "", "### Top risk-increasing factors", ""]
    L += [f"- {c['description']}" for c in p["top_risk_factors"]] or ["- (none)"]
    L += ["", "### Protective factors", ""] + ([f"- {c['description']}" for c in p["protective_factors"]] or ["- (none)"])
    L += ["", "### Recommended support actions", ""]
    L += [f"- **[{a['priority']}] {a['title']}** - {a['reason']}" for a in p["recommended_actions"]] or ["- (none)"]
    L += ["", f"_{p['explanation_note']}_", ""]
    return "\n".join(L)
