// Generates docs/API_ENDPOINTS.md from the same registry that powers Swagger, so the two cannot drift.
import fs from 'node:fs';
import { buildOpenApiDocument } from '../src/docs/openapi';
import { loadConfig } from '../src/config/env';

const doc = buildOpenApiDocument(loadConfig({ NODE_ENV: 'test', JWT_SECRET: 'x'.repeat(40), OTP_PEPPER: 'y'.repeat(40) }));
const rows: Record<string, string[]> = {};
for (const [path, methods] of Object.entries(doc.paths)) {
  for (const [method, op] of Object.entries(methods as Record<string, any>)) {
    const roles = /\*\*Roles:\*\* (.*)/.exec(op.description)?.[1] ?? 'public';
    (rows[op.tags[0]] ??= []).push(`| \`${method.toUpperCase()}\` | \`/api/v1${path}\` | ${op.summary} | ${roles} |`);
  }
}
let md = '# API endpoint reference\n\n> Generated by `npm run docs:api` from `src/docs/openapi.ts`. Interactive docs: `GET /api/docs` (Swagger UI), raw spec: `GET /api/openapi.json`.\n\n';
let total = 0;
for (const tag of doc.tags.map((t) => t.name)) {
  if (!rows[tag]) continue;
  total += rows[tag].length;
  md += `## ${tag}\n\n| Method | Path | Summary | Roles |\n|---|---|---|---|\n${rows[tag].join('\n')}\n\n`;
}
md += `**Total: ${total} endpoints** (plus \`GET /health\`).\n`;
fs.writeFileSync('docs/API_ENDPOINTS.md', md);
console.log(`Wrote docs/API_ENDPOINTS.md (${total} endpoints)`);
